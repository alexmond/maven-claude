def console = new File(basedir, 'build.log').text

// init
assert new File(basedir, '.mvn/extensions.xml').text.contains('<artifactId>claude-maven-plugin</artifactId>')
def settings = new groovy.json.JsonSlurper().parse(new File(basedir, '.claude/settings.json'))
assert settings.permissions.allow.contains('Bash(mvn *)')

// context (resolved through the claude: prefix the extension adds)
def context = new File(basedir, '.claude/maven-context.md').text
assert context.startsWith('<!-- Generated by claude-maven-plugin')
assert context.contains('# Maven project: calc (`demo:calc:1.0`)')
assert context.contains('tests: JUnit 5')

// source
assert console.contains('org.junit.jupiter.api.Assertions')
assert console.contains('  from    org.junit.jupiter:junit-jupiter-api:')
def source = new File(basedir, 'target/claude/sources').listFiles().find { it.name.startsWith('junit-jupiter-api-') }
assert new File(source, 'org/junit/jupiter/api/Assertions.java').text.contains('public class Assertions')
